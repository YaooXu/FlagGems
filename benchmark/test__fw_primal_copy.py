import math

import pytest
import torch
from _pytest.mark.structures import Mark, MarkDecorator

import flag_gems

from . import base, consts, utils

# ``_fw_primal_copy`` starts with an underscore, and ``pytest.mark`` refuses to
# generate a marker via attribute access for such names. Register it directly
# on the MarkGenerator so ``@pytest.mark._fw_primal_copy`` and ``-m
# _fw_primal_copy`` both work.
setattr(
    pytest.mark,
    "_fw_primal_copy",
    MarkDecorator(Mark("_fw_primal_copy", (), {}, _ispytest=True), _ispytest=True),
)

# _fw_primal_copy materializes a fresh copy (the primal at the requested
# forward-mode AD level; for the plain tensors used here the primal is the
# tensor itself) of the input, so each case needs input + output (2x one
# tensor's memory per case). The default shape set contains 1G-element core
# shapes whose fp32 input+output would need ~8 GiB and OOM on busy GPUs; cap
# the shapes while keeping performance-relevant sizes (2**26 elements =
# 256 MiB fp32 per tensor).
MAX_ELEMENTS = 2**26

# _fw_primal_copy requires (self, level); the public pointwise families pass
# only the tensor(s), so a two-phase GenericBenchmark injects the constant
# level argument explicitly.
_LEVEL = 0


def _case_fn(shape, dtype):
    del dtype
    yield base.BenchmarkCasePlan(
        shape={"input": shape},
        params={"level": _LEVEL},
        builder_args=(shape,),
    )


def _build_inputs_fn(plan, dtype, device):
    shape = plan.builder_args[0]
    # The reference torch.ops.aten._fw_primal_copy is only callable on
    # inference tensors (the native implementation is guarded by an
    # InferenceMode assert), so the benchmark input is created inside
    # torch.inference_mode().
    with torch.inference_mode():
        inp = utils.generate_tensor_input(shape, dtype, device)
    return inp, {"level": plan.params["level"]}


class FwPrimalCopyBenchmark(base.GenericBenchmark):
    """Two-phase GenericBenchmark that passes the level argument.

    aten::_fw_primal_copy(Tensor self, int level) -> Tensor needs a level
    alongside the tensor, which the unary pointwise families do not supply, so
    the case builder and input builder forward it explicitly.

    Only the .default overload is benchmarked. The autogenerated .out overload
    is fully covered by the correctness tests; its native reference can only be
    invoked inside torch.inference_mode() on inference tensors (an internal
    InferenceMode guard), which the benchmark timing path (which calls the
    candidate directly) cannot satisfy.
    """

    def set_shapes(self, shape_file_path=None):
        super().set_shapes(shape_file_path)
        self.shapes = [
            shape for shape in self.shapes if math.prod(shape) <= MAX_ELEMENTS
        ]


@pytest.mark._fw_primal_copy
def test__fw_primal_copy():
    bench = FwPrimalCopyBenchmark(
        op_name="_fw_primal_copy",
        case_fn=_case_fn,
        build_inputs_fn=_build_inputs_fn,
        torch_op=torch.ops.aten._fw_primal_copy,
        gems_op=getattr(flag_gems, "_fw_primal_copy", None),
        dtypes=consts.FLOAT_DTYPES,
    )
    bench.run()
